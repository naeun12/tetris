/*
=========================================================
 GET 90° KICKS
=========================================================
*/

export const getKicks = (type, from, to) => {
  const key = `${from}>${to}`;

  // I
  if (type === "I") {
    return I_KICKS[key] || [[0, 0]];
  }

  // O
  if (type === "O") {
    return [[0, 0]];
  }

  // J/L/S/Z/T
  return JLSTZ_KICKS[key] || [[0, 0]];
};

/*
=========================================================
 GET 180° KICKS
=========================================================
*/

export const get180Kicks = (type) => {
  if (type === "I") {
    return I_180_KICKS;
  }

  if (type === "O") {
    return [[0, 0]];
  }

  return JLSTZ_180_KICKS;
};
